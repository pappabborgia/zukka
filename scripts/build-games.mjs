// Bundles the built-in games (games/<id>/game.html + meta.json) into a module for the games origin.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const gamesDir = join(root, "games");
const out = join(root, "apps/play/src/generated/builtin-games.ts");
const catalogOut = join(root, "apps/web/src/generated/builtin-catalog.ts");

const games = {};
const catalog = [];
for (const id of readdirSync(gamesDir).sort()) {
  const file = join(gamesDir, id, "game.html");
  if (!existsSync(file)) continue;
  if (!/^[a-z0-9-]+$/.test(id)) throw new Error(`bad game id: ${id}`);
  const meta = JSON.parse(readFileSync(join(gamesDir, id, "meta.json"), "utf8"));
  games[id] = { title: meta.title, html: readFileSync(file, "utf8") };
  catalog.push({ id, title: meta.title, description: meta.description, subjects: meta.subjects, years: meta.years, listed: meta.listed === true });
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "// Generated by scripts/build-games.mjs. Do not edit.\n" +
    "export const BUILTIN_GAMES: Record<string, { title: string; html: string }> = " +
    JSON.stringify(games) +
    ";\n",
);
mkdirSync(dirname(catalogOut), { recursive: true });
writeFileSync(
  catalogOut,
  "// Generated by scripts/build-games.mjs. Do not edit.\n" +
    "export interface BuiltinGame { id: string; title: string; description: string; subjects: string[]; years: number[]; listed: boolean }\n" +
    "export const BUILTIN_CATALOG: BuiltinGame[] = " +
    JSON.stringify(catalog, null, 2) +
    ";\n",
);
console.log(`built-in games: ${Object.keys(games).join(", ")}`);
