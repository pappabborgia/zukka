// Bundles the built-in games (games/<id>/game.html + meta.json) into a module for the games origin.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const gamesDir = join(root, "games");
const out = join(root, "apps/play/src/generated/builtin-games.ts");
const catalogOut = join(root, "apps/web/src/generated/builtin-catalog.ts");

const games = {};
const catalog = [];
const enginesDir = join(root, "engines");
const templates = {};
for (const id of readdirSync(enginesDir).sort()) {
  const file = join(enginesDir, id, "template.html");
  if (existsSync(file)) templates[id] = readFileSync(file, "utf8");
}
for (const id of readdirSync(gamesDir).sort()) {
  if (!existsSync(join(gamesDir, id, "meta.json"))) continue;
  if (!/^[a-z0-9-]+$/.test(id)) throw new Error(`bad game id: ${id}`);
  const meta = JSON.parse(readFileSync(join(gamesDir, id, "meta.json"), "utf8"));
  // a built-in game is either its own game.html, or an engine template with its default config
  const file = meta.engine ? join(enginesDir, meta.engine, "template.html") : join(gamesDir, id, "game.html");
  if (!existsSync(file)) throw new Error(`missing ${file}`);
  games[id] = { title: meta.title, html: readFileSync(file, "utf8") };
  catalog.push({ id, title: meta.title, description: meta.description, subjects: meta.subjects, years: meta.years, listed: meta.listed === true, engine: meta.engine ?? null });
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  "// Generated by scripts/build-games.mjs. Do not edit.\n" +
    "export const BUILTIN_GAMES: Record<string, { title: string; html: string }> = " +
    JSON.stringify(games) +
    ";\n",
);
// engine templates, for the games origin to build created games from their config
writeFileSync(
  join(root, "apps/play/src/generated/engine-templates.ts"),
  "// Generated by scripts/build-games.mjs. Do not edit.\n" +
    "export const ENGINE_TEMPLATES: Record<string, string> = " +
    JSON.stringify(templates) +
    ";\n",
);
// for the main site: sizes of the templates and of their default configs (to check the 700 KB limit when saving)
const sizes = {};
for (const [id, tpl] of Object.entries(templates)) {
  const i = tpl.indexOf("/*ZUKKA_CONFIG*/"), j = tpl.indexOf("/*END_ZUKKA_CONFIG*/");
  sizes[id] = { templateBytes: Buffer.byteLength(tpl), defaultConfigBytes: Buffer.byteLength(tpl.slice(i + 16, j)), defaultConfig: JSON.parse(tpl.slice(i + 16, j).replace(/<\\\//g, "</")) };
}
mkdirSync(dirname(catalogOut), { recursive: true });
writeFileSync(
  join(root, "apps/web/src/generated/engine-defaults.ts"),
  "// Generated by scripts/build-games.mjs. Do not edit.\n" +
    "export const ENGINE_DEFAULTS: Record<string, { templateBytes: number; defaultConfigBytes: number; defaultConfig: unknown }> = " +
    JSON.stringify(sizes) +
    ";\n",
);
writeFileSync(
  catalogOut,
  "// Generated by scripts/build-games.mjs. Do not edit.\n" +
    "export interface BuiltinGame { id: string; title: string; description: string; subjects: string[]; years: number[]; listed: boolean; engine: string | null }\n" +
    "export const BUILTIN_CATALOG: BuiltinGame[] = " +
    JSON.stringify(catalog, null, 2) +
    ";\n",
);
console.log(`built-in games: ${Object.keys(games).join(", ")}`);
